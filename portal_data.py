# ──────────────────────────── 시뮬레이션 로직 ────────────────────────────
def simulate(P, T0, R1, BONUS, C_pct, S_pct):
    """계약 1건 기준 시나리오별 (1차년 수령액, 총수령액). 금액 단위: P와 동일(만원)."""
    C = P * C_pct / 100.0
    S = min(P * S_pct / 100.0, C)          # 선지급 ≤ 계약체결비용 100%
    cur1 = P * T0 / 100.0 * R1 / 100.0 + P * BONUS / 100.0
    curT = P * T0 / 100.0 + P * BONUS / 100.0
    cap1 = min(cur1, P * 12)               # 1,200% 룰 (보장성, 증권 단위)
    m4 = min(C * 0.015, C * 0.90 / 48)     # 4년 분급: 월 1.5% 이내, 총량 90%
    m7 = min(C * 0.008, C * 1.00 / 84)     # 7년 분급: 월 0.8% 이내, 총량 100%
    l7 = C * 0.004                         # 장기유지(5년↑, 61~84차월 가정)
    return {
        "현행": (cur1, curT),
        "'26.7 (1,200%룰)": (cap1, min(curT, P * 12)),
        "'27.1 (4년 분급)": (S + m4 * 12, S + m4 * 48),
        "'29.1 (7년 분급)": (S + m7 * 12, S + m7 * 84 + l7 * 24),
    }


def refund_rate(m, r12, r24, r36):
    """3점(12/24/36차월) 선형 보간 환급률 (0~1)."""
    if m <= 12:
        return r12 * m / 12
    if m <= 24:
        return r12 + (r24 - r12) * (m - 12) / 12
    return r24 + (r36 - r24) * (m - 24) / 12


def arbitrage_table(P, fee, rates):
    """차월별 차익거래 판정. rates: 길이 36의 환급률 리스트(0~1).

    확정 산식: 수수료등 + 해약환급금 − 환수금 > 납입보험료 → 차익거래.
    """
    rows = []
    for m in range(1, 37):
        paid = P * m
        cv = paid * rates[m - 1]
        agent = fee + cv
        rows.append(dict(차월=m, 납입누계=paid, 예상환급금=round(cv, 1),
                         설계사측수취=round(agent, 1), 위험=agent > paid))
    return pd.DataFrame(rows)


# ──────────────────────────── 해약환급률표 로더 ────────────────────────────
def _parse_rate_file(path: Path) -> pd.DataFrame | None:
    """환급률표 파싱 — 헤더 이름으로 열을 찾아 양식 변형(선행 '구분' 열 등)에 대응.

    필요 헤더: 회사명·상품명·납입기간(·종구분). 차월 열은 다음 행의 '1차월' 위치부터 최대 36개.
    """
    try:
        raw = pd.read_excel(path, header=None, engine="openpyxl", sheet_name=0)
    except Exception:
        return None
    hdr = None
    for i in range(min(12, len(raw))):
        vals = [str(c).replace(" ", "").strip() for c in raw.iloc[i] if pd.notna(c)]
        if "회사명" in vals:
            hdr = i
            break
    if hdr is None or hdr + 2 >= len(raw):
        return None
    header = [str(c).replace(" ", "").split("\n")[0].strip() if pd.notna(c) else ""
              for c in raw.iloc[hdr]]

    def col(name):
        return header.index(name) if name in header else None

    c_comp, c_prod, c_kind, c_term = col("회사명"), col("상품명"), col("종구분"), col("납입기간")
    if None in (c_comp, c_prod, c_term):
        return None
    sub = [str(c).replace(" ", "").strip() if pd.notna(c) else "" for c in raw.iloc[hdr + 1]]
    r0 = sub.index("1차월") if "1차월" in sub else c_term + 1
    body = raw.iloc[hdr + 2:]
    n_rate = max(0, min(36, body.shape[1] - r0))
    if n_rate == 0:
        return None
    out = pd.DataFrame({
        "회사명": body.iloc[:, c_comp],
        "상품명": body.iloc[:, c_prod],
        "종구분": body.iloc[:, c_kind] if c_kind is not None else "",
        "납입기간": body.iloc[:, c_term],
    })
    for k in range(n_rate):
        out[f"{k + 1}차월"] = pd.to_numeric(body.iloc[:, r0 + k], errors="coerce")
    out = out.dropna(subset=["회사명", "상품명"])
    out = out[out["회사명"].astype(str).str.strip() != ""]
    out["파일"] = path.name
    return out if len(out) else None


def load_rate_tables(dirs=None) -> tuple[pd.DataFrame, list[str]]:
    """폴더들에서 '환급' 포함 xlsx를 모두 파싱해 합친다. 반환: (데이터, 로그)."""
    frames, logs = [], []
    seen_names = set()
    for d in (dirs or DEFAULT_RATE_DIRS):
        p = Path(d)
        if not p.is_dir():
            continue
        for f in sorted(list(p.glob("*.xlsx")) + list(p.glob("*.xlsm"))):
            if "환급" not in f.name or f.name in seen_names:
                continue
            seen_names.add(f.name)
            try:
                if f.read_bytes()[:20].startswith(b"<!-- Fasoo"):
                    logs.append(f"🔒 {f.name}: DRM(Fasoo) 암호화 — 보안 해제 후 다시 업로드 필요")
                    continue
            except OSError:
                pass
            df = _parse_rate_file(f)
            if df is not None:
                frames.append(df)
                logs.append(f"✅ {f.name}: {len(df)}행")
            else:
                logs.append(f"⚠️ {f.name}: 환급률 숫자 없음/양식 다름 — 건너뜀")
    if frames:
        return pd.concat(frames, ignore_index=True), logs
    return pd.DataFrame(), logs
